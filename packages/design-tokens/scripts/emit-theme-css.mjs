// Emits the brand layer as CSS custom properties, from the same TypeScript the
// email templates import. Runs after `vp pack`, against the built ESM output,
// so it needs no TypeScript loader.
//
// It emits layer one only. The mapping from these primitives onto the
// component library's contract is a design judgement and stays hand-written in
// packages/ui/src/styles/globals.css.

import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  color,
  cornerGeometry,
  duration,
  easing,
  fontStack,
  productImage,
  radius,
  textSize,
} from "../dist/index.mjs";

const kebab = (name) => name.replaceAll(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

function declarations() {
  const lines = [];

  lines.push("  /* Colour */");
  for (const [name, value] of Object.entries(color)) {
    lines.push(`  --mze-${kebab(name)}: ${value.oklch};`);
  }

  lines.push("", "  /* Type */");
  for (const [role, stack] of Object.entries(fontStack.web)) {
    lines.push(`  --mze-font-${role}: ${stack};`);
  }
  for (const [step, { size, leading }] of Object.entries(textSize)) {
    lines.push(`  --mze-text-${step}: ${size};`);
    lines.push(`  --mze-leading-${step}: ${leading};`);
  }

  lines.push("", "  /* Geometry */");
  lines.push(`  --mze-radius: ${radius};`);
  lines.push(`  --mze-corner-shape: ${cornerGeometry};`);
  lines.push(`  --mze-product-aspect: ${productImage.aspect};`);
  lines.push(`  --mze-product-padding: ${productImage.padding};`);

  lines.push("", "  /* Motion */");
  for (const [step, value] of Object.entries(duration)) {
    lines.push(`  --mze-duration-${step}: ${value};`);
  }
  for (const [name, value] of Object.entries(easing)) {
    lines.push(`  --mze-ease-${name}: ${value};`);
  }

  return lines;
}

const css = [
  "/* Generated by @mze-store/design-tokens. Edit src/, not this file. */",
  ":root {",
  ...declarations(),
  "}",
  "",
].join("\n");

const outputPath = join(dirname(fileURLToPath(import.meta.url)), "..", "dist", "theme.css");
await writeFile(outputPath, css, "utf8");
